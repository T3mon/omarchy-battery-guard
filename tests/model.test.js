const assert = require("assert")
const M = require("../Model.js")

const cfg = M.readSettings({})
assert.deepStrictEqual(cfg, { low: 20, high: 80, travel: false, repeatMinutes: 5 })
assert.deepStrictEqual(M.readSettings({ low: 45, high: 50 }), { low: 45, high: 55, travel: false, repeatMinutes: 5 })
assert.strictEqual(M.readSettings({ low: "abc" }).low, 20)

assert.strictEqual(M.withSetting({}, "low", 80).low, 50)
assert.strictEqual(M.withSetting({ high: 55 }, "low", 50).low, 45)
assert.strictEqual(M.withSetting({}, "high", 10).high, 50)
assert.strictEqual(M.withSetting({}, "travel", true).travel, true)

assert.strictEqual(M.level(null), -1)
assert.strictEqual(M.level({ isPresent: true, percentage: 0.794 }), 79)

assert.strictEqual(M.wantedReminder(20, true, cfg), "plugIn")
assert.strictEqual(M.wantedReminder(21, true, cfg), "")
assert.strictEqual(M.wantedReminder(80, false, cfg), "unplug")
assert.strictEqual(M.wantedReminder(10, false, cfg), "")
assert.strictEqual(M.wantedReminder(90, true, cfg), "")
const travel = M.readSettings({ travel: true })
assert.strictEqual(M.wantedReminder(85, false, travel), "")
assert.strictEqual(M.wantedReminder(100, false, travel), "full")
assert.strictEqual(M.wantedReminder(15, true, travel), "plugIn")

let r = M.step(null, "unplug", 1000, cfg)
assert.strictEqual(r.notify, true)
r = M.step(r.memory, "unplug", 1000 + 60000, cfg)
assert.strictEqual(r.notify, false)
r = M.step(r.memory, "unplug", 1000 + 5 * 60000, cfg)
assert.strictEqual(r.notify, true)
r = M.step(r.memory, "", 999999, cfg)
assert.deepStrictEqual(r.memory, { kind: "", at: 0 })

r = M.step(null, "full", 0, travel)
assert.strictEqual(r.notify, true)
r = M.step(r.memory, "full", 99999999, travel)
assert.strictEqual(r.notify, false)

const noRepeat = M.readSettings({ repeatMinutes: 0 })
r = M.step({ kind: "plugIn", at: 0 }, "plugIn", 99999999, noRepeat)
assert.strictEqual(r.notify, false)

assert.strictEqual(M.statusKey(50, true, cfg), "status.onBattery")
assert.strictEqual(M.statusKey(50, false, cfg), "status.charging")
assert.strictEqual(M.statusKey(50, false, travel), "status.chargingTravel")
assert.strictEqual(M.statusKey(81, false, cfg), "status.unplug")

assert.deepStrictEqual(M.parseKeyValue("percentage\t86%\nstate\tdischarging\nbad"), { percentage: "86%", state: "discharging" })
assert.deepStrictEqual(M.parseProfiles("power-saver\t0\nbalanced\t1\n<b>\t1\n"), { profiles: ["power-saver", "balanced"], active: "balanced" })
assert.strictEqual(M.parsePalette('yellow = "#ebcb8b"\ngreen = "#a3be8c"').green, "#a3be8c")
assert.strictEqual(M.flow({ state: "charging" }, false), "charging")
assert.strictEqual(M.flow({ state: "holding" }, false), "idle")
assert.strictEqual(M.flow({}, true), "discharging")
console.log("ok")
